#!/usr/bin/env bash
# One-time setup of the PUBLIC media host (GitHub Pages). Everything pushed there is
# visible to anyone on the internet, which is what Buffer/Meta need to fetch media.
# Requires: gh (logged in). Usage: bash scripts/setup-media-host.sh [owner/repo] [clone-dir]
set -euo pipefail
REPO="${1:-GabrieleCalderone/risthome-media}"
DIR="${2:-$HOME/Projects/risthome-media}"
if ! gh repo view "$REPO" >/dev/null 2>&1; then
  gh repo create "$REPO" --public --description "Public media host for RistHome social posts (GitHub Pages)"
  echo "created $REPO"
fi
if [ ! -d "$DIR/.git" ]; then
  git clone -q "https://github.com/$REPO.git" "$DIR"
fi
cd "$DIR"
if [ ! -f README.md ]; then
  printf '# risthome-media\n\nPublic media for RistHome social posts, served by GitHub Pages. Generated by risthome-ai-factory.\n' > README.md
  touch .nojekyll
  git add -A && git commit -qm "chore: init media host" && git branch -M main && git push -q -u origin main
fi
gh api -X POST "repos/$REPO/pages" -f "source[branch]=main" -f "source[path]=/" >/dev/null 2>&1 || true
echo "pages: $(gh api "repos/$REPO/pages" --jq '.html_url + " (" + .status + ")"')"
echo "set MEDIA_BASE_URL in .env if the URL above differs from https://$(echo "$REPO" | cut -d/ -f1 | tr 'A-Z' 'a-z').github.io/$(echo "$REPO" | cut -d/ -f2)"
