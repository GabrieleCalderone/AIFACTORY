/**
 * Build docs/performance.md from data/experiments.csv: a funnel per variant and an
 * aggregate per archetype (the knowledge base's "historical performance"). Empty
 * cells print as "–"; nothing is estimated.
 *
 *   node scripts/report.ts [--out docs/performance.md]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { readExperiments } from "../src/lib/data.ts";
import { pct, wilson } from "../src/lib/stats.ts";
import type { ExperimentRow } from "../src/schemas/experiment.ts";

const { values } = parseArgs({ options: { out: { type: "string", default: "docs/performance.md" } } });
const { records, issues } = readExperiments();
if (issues.length) {
  for (const i of issues) console.error(`${i.file}:${i.row}: ${i.message}`);
  process.exit(1);
}
const archetypes = (JSON.parse(readFileSync("content/archetypes.json", "utf8")) as { archetypes: { id: string; name: string; service?: string }[] }).archetypes;
const products = (JSON.parse(readFileSync("content/products.json", "utf8")) as { products: Record<string, { name: string; avgTicketEur: number; marginAssumption: number }> }).products;
const spend = existsSync("data/genai-spend.json") ? (JSON.parse(readFileSync("data/genai-spend.json", "utf8")) as { usd: number; slug?: string }[]) : [];
const dash = "–";
const n = (v: number | null) => (v === null ? dash : String(v));
const ratio = (num: number | null, den: number | null) => (num === null || den === null || den === 0 ? dash : pct(num / den, 1));
const ci = (num: number | null, den: number | null) => {
  if (num === null || den === null || den === 0) return dash;
  const w = wilson(num, den);
  return `${pct(w.rate, 1)} [${pct(w.low, 1)}–${pct(w.high, 1)}]`;
};
const sum = (rows: ExperimentRow[], key: keyof ExperimentRow): number | null => {
  const vals = rows.map((r) => r[key]).filter((v): v is number => typeof v === "number");
  return vals.length === 0 ? null : vals.reduce((a, b) => a + b, 0);
};

const lines: string[] = [];
lines.push("# Creative performance", "", `Generated by \`node scripts/report.ts\` on ${new Date().toISOString().slice(0, 10)} from \`data/experiments.csv\`. A dash means not measured. Intervals are 95% Wilson.`, "");
lines.push("## Funnel per variant", "", "| Experiment | Var | Post | Archetype | Status | Reach | Plays | Avg watch s | Saves/reach | Link clicks | Inquiries (qualified) | Bookings | Revenue EUR | Margin EUR |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
for (const r of records) {
  lines.push(`| ${r.experiment_id} | ${r.variant_id} | ${r.post_slug} | ${r.archetype} | ${r.status} | ${n(r.reach)} | ${n(r.plays)} | ${n(r.avg_watch_time_sec)} | ${ratio(r.saves, r.reach)} | ${n(r.link_clicks)} | ${n(r.inquiries)} (${n(r.qualified_inquiries)}) | ${n(r.bookings)} | ${n(r.revenue_eur)} | ${n(r.contribution_margin_eur)} |`);
}
lines.push("", "## Hypotheses", "");
for (const r of records) lines.push(`- **${r.experiment_id}/${r.variant_id}** (${r.post_slug}): ${r.hypothesis}. Success: ${r.success_metric}.`);
lines.push("", "## Historical performance per archetype", "", "| Archetype | Posts | Measured | Save rate (pooled) | Inquiries per 1,000 plays | Bookings | Revenue EUR |", "|---|---|---|---|---|---|---|");
for (const a of archetypes) {
  const rows = records.filter((r) => r.archetype === a.id);
  const measured = rows.filter((r) => r.status === "measured");
  const saves = sum(measured, "saves");
  const reach = sum(measured, "reach");
  const inq = sum(measured, "qualified_inquiries");
  const plays = sum(measured, "plays");
  const perK = inq === null || plays === null || plays === 0 ? dash : (1000 * inq / plays).toFixed(2);
  lines.push(`| ${a.id} ${a.name} | ${rows.length} | ${measured.length} | ${ci(saves, reach)} | ${perK} | ${n(sum(measured, "bookings"))} | ${n(sum(measured, "revenue_eur"))} |`);
}
// The three signals Instagram names for ranking, read per series; a series with few measured posts says nothing yet.
const MIN_MEASURED = 5;
const mean = (rows: ExperimentRow[], key: keyof ExperimentRow): string => {
  const values = rows.map((r) => r[key]).filter((v): v is number => typeof v === "number");
  return values.length ? (values.reduce((a, b) => a + b, 0) / values.length).toFixed(1) : dash;
};
lines.push("", "## Series signals (average watch time, likes per reach, sends per reach)", "", `A series is read only from ${MIN_MEASURED} measured posts on; below that the figures are shown but no conclusion is drawn.`, "", "| Series | Measured | Avg watch s | Likes / reach | Sends / reach | Reading |", "|---|---|---|---|---|---|");
for (const a of archetypes) {
  const measured = records.filter((r) => r.archetype === a.id && r.status === "measured");
  lines.push(`| ${a.id} | ${measured.length} | ${mean(measured, "avg_watch_time_sec")} | ${ratio(sum(measured, "likes"), sum(measured, "reach"))} | ${ratio(sum(measured, "shares"), sum(measured, "reach"))} | ${measured.length >= MIN_MEASURED ? "readable" : `wait (${measured.length}/${MIN_MEASURED})`} |`);
}
lines.push("", "## Revenue view per product", "", "| Product | Posts | Qualified inquiries | Bookings | Revenue EUR | Est. margin EUR (assumption) | AI cost EUR | Cost per booking |", "|---|---|---|---|---|---|---|---|");
for (const [key, p] of Object.entries(products)) {
  const archIds = archetypes.filter((a) => a.service === key).map((a) => a.id);
  const rows = records.filter((r) => archIds.includes(r.archetype));
  const inq = sum(rows, "qualified_inquiries");
  const bookings = sum(rows, "bookings");
  const revenue = sum(rows, "revenue_eur");
  const ai = spend.filter((s) => s.slug && rows.some((r) => r.post_slug === s.slug)).reduce((a, b) => a + b.usd * 0.95, 0);
  const margin = revenue === null ? dash : (revenue * p.marginAssumption).toFixed(0);
  const cpb = bookings && bookings > 0 ? (ai / bookings).toFixed(2) : dash;
  lines.push(`| ${p.name} | ${rows.length} | ${n(inq)} | ${n(bookings)} | ${n(revenue)} | ${margin} | ${ai.toFixed(2)} | ${cpb} |`);
}
lines.push("", "Production cost outside AI generation is EUR 0 (subscription and free tiers); margins use the 60% working assumption until the cash book says otherwise.", "");
lines.push("Winning patterns are promoted into `content/archetypes.json` only after at least two measured posts per archetype and non-overlapping intervals (`node scripts/compare.ts`).", "");
writeFileSync(values.out, lines.join("\n"));
console.log(`wrote ${values.out} (${records.length} variants)`);
